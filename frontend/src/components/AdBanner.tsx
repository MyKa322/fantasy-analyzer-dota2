// Рекламный баннер над содержимым вкладок.
//
// Отдельным файлом, а не строкой в App: адрес с реферальным кодом и параметрами
// — единственное, что в нём меняется, и искать его в разметке шапки не надо.

import { useT, type Locale } from "../i18n";

const ENDPOINT = "https://bads.waevue.cfd/banner/v1";
const REF = "ref_ETXDWBMV";

/**
 * Язык баннера.
 *
 * У сети переведены ровно два языка — английский и русский, остальные значения
 * параметра `lang` она игнорирует и берёт язык браузера. Отсюда и картина,
 * которая была до этого: английская страница с русским баннером, потому что в
 * браузере стоял русский. Поэтому язык задаём явно: русский — только русской
 * версии сайта, всем прочим английский.
 *
 * Украинского у сети нет, и сама она в этом случае отдаёт русский — здесь
 * выбран английский: это перевод, а не язык соседней страны.
 */
const BANNER_LANG: Record<Locale, "en" | "ru"> = {
  en: "en",
  ru: "ru",
  uk: "en",
  zh: "en",
  es: "en",
  pt: "en",
  de: "en",
  fr: "en",
  pl: "en",
  tr: "en",
  id: "en",
  vi: "en",
};

export default function AdBanner() {
  const { locale } = useT();
  const src = `${ENDPOINT}?refid=${REF}&to=bot&bg=0b0c0e&lang=${BANNER_LANG[locale]}`;

  return (
    // Баннер верстается по ширине своей врезки (container queries), и ниже
    // 331px он перестраивается в столбик: логотип, заголовок, кнопка. В строку
    // ему хватает 140px, столбиком нужно 176 — иначе кнопка «Открыть в
    // Telegram» обрезается, у баннера внутри overflow: hidden.
    //
    // Точка переключения считается от ширины самой врезки, а не окна: отступы
    // страницы поменяются — арифметику breakpoint'а править не придётся.
    <div className="@container mb-6">
      <iframe
        src={src}
        title="waevue"
        loading="lazy"
        // Высота фиксированная и в атрибуте, и в классе: место под баннер
        // занято до его загрузки, иначе страница дёргается уже под курсором.
        height={140}
        className="block h-[140px] w-full border-0 @max-[331px]:h-[180px]"
      />
    </div>
  );
}
